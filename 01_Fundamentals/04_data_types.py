# Python Data Types

# String
name = "Hanish"

# Integer
age = 30

# Float
height = 5.9

# Boolean
is_learning = True

print(name)
print(age)
print(height)
print(is_learning)


# Checking data types

print(type(name))
print(type(age))
print(type(height))
print(type(is_learning))


# Different types behave differently

number = 10
text = "10"

print(number + 5)
print(text + "5")


# A variable can be assigned a value of a different type

value = 10
print(type(value))

value = "Python"
print(type(value))